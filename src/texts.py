MODE_NAMES = {'directed': 'только обращения', 'all': 'все сообщения'}
PRIVACY_NAMES = {None: 'неизвестно', True: 'включена', False: 'выключена'}


def status(*, mode, paused, history_limit, stored, summary, images, voice, web, privacy, cooldown, voice_limit,
           provider, model, vision, retention, user_rpm, chat_rpm, media_rpm, chat_spent, chat_budget,
           spent, budget):
    lines = [
        SETTINGS_TITLE,
        f'Режим: {MODE_NAMES.get(mode, mode)}' + (' · ⏸ пауза' if paused else ''),
        f'Фото: {images} · Голосовые: {voice} · Поиск: {web}',
        f'Память: {stored} из {history_limit} сообщений' + (', есть сводка' if summary else ''),
        f'Хранение: {retention} дн.' if retention else 'Хранение: без срока',
        f'Пауза для ответов без обращения: {cooldown} с · Голосовые до {voice_limit} с',
        f'Лимиты в минуту: пользователь {user_rpm}, группа {chat_rpm}, медиа {media_rpm}',
        f'Провайдер: {provider}, модель {model}' + (f', зрение {vision}' if vision else ''),
        f'Приватность BotFather (при запуске): {PRIVACY_NAMES.get(privacy, privacy)}',
        f'Расходы группы: ${chat_spent:.4f} из ${chat_budget}; всего: ${spent:.4f} из ${budget}',
    ]
    return '\n'.join(lines)


